/// Build an [`EvalContext`] from the `globals` half of an input
/// together with the fixture-level `globalState` block and the
/// feature's `featureState` block.
///
/// The upstream input shape splits state across two scopes:
///
/// - `globals` (the per-input first slot) carries `zoom`,
///   `canonicalID`, `heatmapDensity`, `elevation`, and
///   `availableImages` — values that the renderer would re-derive
///   each draw call.
/// - `globalState` lives at the *fixture* top level (not per-input),
///   because the spec models it as a style-scoped key/value store.
/// - `featureState` lives alongside `properties` inside the
///   per-input feature blob.
///
/// We collapse all three into a single `EvalContext` here so the
/// per-fixture run loop stays simple — no operator needs to know
/// *where* its input came from.
fn eval_context_from(
    globals: &Json,
    fixture_global_state: Option<&Json>,
    feature: &Json,
) -> EvalContext {
    let zoom = globals.get("zoom").and_then(Json::as_f64).unwrap_or(0.0);
    let canonical = globals.get("canonicalID").and_then(canonical_from_json);
    let heatmap_density = globals
        .get("heatmapDensity")
        .and_then(Json::as_f64)
        .unwrap_or(0.0);
    let elevation = globals
        .get("elevation")
        .and_then(Json::as_f64)
        .unwrap_or(0.0);
    let available_images = globals
        .get("availableImages")
        .and_then(Json::as_array)
        .map(|arr| {
            arr.iter()
                .filter_map(Json::as_str)
                .map(str::to_owned)
                .collect::<HashSet<String>>()
        })
        .unwrap_or_default();
    let global_state = fixture_global_state
        .and_then(json_object_to_value_map)
        .unwrap_or_default();
    let feature_state = feature
        .get("featureState")
        .and_then(json_object_to_value_map)
        .unwrap_or_default();
    EvalContext {
        zoom,
        canonical,
        heatmap_density,
        elevation,
        available_images,
        global_state,
        feature_state,
        ..Default::default()
    }
}

/// Convert a JSON object into a `HashMap<String, ExprValue>` for the
/// two state maps. Each value passes through `json_to_expr_value` so
/// nested arrays/objects survive structurally — `feature-state` can
/// hand back any value type, and the outer assertion (`number`,
/// `string`, …) is what surfaces a type mismatch.
fn json_object_to_value_map(v: &Json) -> Option<HashMap<String, ExprValue>> {
    let obj = v.as_object()?;
    Some(
        obj.iter()
            .map(|(k, v)| (k.clone(), json_to_expr_value(v)))
            .collect(),
    )
}

/// Recursive `serde_json::Value` → `ExprValue` conversion for state
/// maps. We can't reuse `json_to_mvt_value` (it produces an
/// `MvtValue`, the property-layer type); state values are richer and
/// shorter-lived, so a direct mapping into the expression value type
/// is the right shape.
fn json_to_expr_value(v: &Json) -> ExprValue {
    match v {
        Json::Null => ExprValue::Null,
        Json::Bool(b) => ExprValue::Bool(*b),
        Json::Number(n) => n.as_f64().map(ExprValue::Number).unwrap_or(ExprValue::Null),
        Json::String(s) => ExprValue::String(s.clone()),
        Json::Array(items) => ExprValue::Array(items.iter().map(json_to_expr_value).collect()),
        Json::Object(map) => {
            let mut out = std::collections::BTreeMap::new();
            for (k, v) in map {
                out.insert(k.clone(), json_to_expr_value(v));
            }
            ExprValue::Object(out)
        }
    }
}

/// Parse a `canonicalID` block — the upstream test runner emits
/// `{ "z": …, "x": …, "y": … }` with non-negative integer values. We
/// silently return `None` for malformed shapes; the runner will
/// surface that as a mismatch on the operator output.
fn canonical_from_json(v: &Json) -> Option<CanonicalTileID> {
    let obj = v.as_object()?;
    let z = obj.get("z")?.as_u64()? as u8;
    let x = obj.get("x")?.as_u64()? as u32;
    let y = obj.get("y")?.as_u64()? as u32;
    Some(CanonicalTileID { z, x, y })
}

/// Build a [`Feature`] from the `feature` half of an input.
///
/// Property values are mapped JSON → `MvtValue` recursively. `MvtValue`
/// has richer-than-MVT `Null`, `Array`, and `Object` variants for
/// exactly this purpose — they never appear in proto-decoded tiles but
/// the style-spec fixtures rely on feeding structural property values
/// through to expression evaluation.
///
/// Property nulls survive as `MvtValue::Null` (rather than being
/// dropped) because the fixtures explicitly distinguish "key present
/// with null value" from "key absent" — `["typeof", ["get", "x"]]` is
/// `"null"` in the first case and `"null"` in the second too, but
/// `["number", ["get", "x"], -1]` returns the fallback in both cases,
/// which only happens cleanly when the property exists as null.
fn feature_from(feature: &Json, canonical: Option<CanonicalTileID>) -> Feature {
    let mut properties: HashMap<String, MvtValue> = HashMap::new();

    if let Some(obj) = feature.get("properties").and_then(Json::as_object) {
        for (k, v) in obj {
            properties.insert(k.clone(), json_to_mvt_value(v));
        }
    }

    let id = feature.get("id").and_then(Json::as_u64);
    let geometry = feature
        .get("geometry")
        .and_then(|g| geometry_from_json(g, canonical))
        .unwrap_or(Geometry::Unknown);

    Feature {
        id,
        properties,
        geometry,
    }
}

// ==============================================================================
// GeoJSON → tile-coord `Geometry` projection
//
// The fixtures store feature geometry as bare GeoJSON in lng/lat
// coordinates. Upstream's `test/lib/geometry.ts` projects those into
// the canonical tile's local pixel frame (with the tile-origin shift
// subtracted) before handing the feature to the expression evaluator.
// We follow the same convention here so geometry-aware operators see
// the same numbers they would in JS.
//
// When no `canonicalID` is present we fall back to passing coordinates
// through verbatim — `geometry-type` only cares about the variant, and
// the operators that need geographic projection (`within`, `distance`)
// already bail out without a canonical tile.
// ==============================================================================

const TILE_EXTENT: f64 = 8192.0;

fn mercator_x_from_lng(lng: f64) -> f64 {
    (180.0 + lng) / 360.0
}

fn mercator_y_from_lat(lat: f64) -> f64 {
    (180.0
        - (180.0 / std::f64::consts::PI)
            * (std::f64::consts::PI / 4.0 + lat * std::f64::consts::PI / 360.0)
                .tan()
                .ln())
        / 360.0
}

/// Project a `(lng, lat)` pair into the rounded tile-local frame the
/// `geo::Geometry` consumer expects. Subtracting the tile-origin
/// shifts matches upstream's `getPoint`, which expresses the point
/// relative to the canonical tile so per-feature evaluation stays in
/// small integers regardless of zoom level.
fn project_lnglat(coord: &Json, canonical: Option<CanonicalTileID>) -> Option<(f64, f64)> {
    let arr = coord.as_array()?;
    if arr.len() < 2 {
        return None;
    }
    let lng = arr[0].as_f64()?;
    let lat = arr[1].as_f64()?;
    Some(match canonical {
        Some(c) => {
            let mx = mercator_x_from_lng(lng);
            let my = mercator_y_from_lat(lat);
            let tiles = 2f64.powi(c.z as i32);
            let tx = (mx * tiles * TILE_EXTENT).round();
            let ty = (my * tiles * TILE_EXTENT).round();
            (tx - c.x as f64 * TILE_EXTENT, ty - c.y as f64 * TILE_EXTENT)
        }
        // Without a canonical tile we pass coords through unchanged.
        // The only operator that exercises this branch is
        // `geometry-type`, which doesn't care about coordinate values.
        None => (lng, lat),
    })
}

fn project_lnglat_list(
    coords: &Json,
    canonical: Option<CanonicalTileID>,
) -> Option<Vec<(f64, f64)>> {
    coords
        .as_array()?
        .iter()
        .map(|c| project_lnglat(c, canonical))
        .collect()
}

/// Convert a GeoJSON `geometry` value into a `geo::Geometry`. Returns
/// `None` for unknown types or malformed coordinate arrays — the
/// caller defaults to `Geometry::Unknown` in that case so the rest of
/// the fixture still runs.
fn geometry_from_json(g: &Json, canonical: Option<CanonicalTileID>) -> Option<Geometry> {
    let obj = g.as_object()?;
    let kind = obj.get("type")?.as_str()?;
    let coords = obj.get("coordinates")?;
    match kind {
        "Point" => {
            let (x, y) = project_lnglat(coords, canonical)?;
            Some(Geometry::Point(Point::new(x, y)))
        }
        "MultiPoint" => {
            let pts: Vec<(f64, f64)> = project_lnglat_list(coords, canonical)?;
            Some(Geometry::MultiPoint(MultiPoint(
                pts.into_iter().map(|(x, y)| Point::new(x, y)).collect(),
            )))
        }
        "LineString" => {
            let pts = project_lnglat_list(coords, canonical)?;
            Some(Geometry::LineString(LineString::from(pts)))
        }
        "MultiLineString" => {
            let lines: Option<Vec<LineString<f64>>> = coords
                .as_array()?
                .iter()
                .map(|l| project_lnglat_list(l, canonical).map(LineString::from))
                .collect();
            Some(Geometry::MultiLineString(MultiLineString(lines?)))
        }
        "Polygon" => Some(Geometry::Polygon(polygon_from_json(coords, canonical)?)),
        "MultiPolygon" => {
            let polys: Option<Vec<Polygon<f64>>> = coords
                .as_array()?
                .iter()
                .map(|p| polygon_from_json(p, canonical))
                .collect();
            Some(Geometry::MultiPolygon(MultiPolygon(polys?)))
        }
        _ => None,
    }
}

fn polygon_from_json(coords: &Json, canonical: Option<CanonicalTileID>) -> Option<Polygon<f64>> {
    let rings = coords.as_array()?;
    let mut iter = rings.iter();
    let exterior = LineString::from(project_lnglat_list(iter.next()?, canonical)?);
    let interiors: Option<Vec<LineString<f64>>> = iter
        .map(|r| project_lnglat_list(r, canonical).map(LineString::from))
        .collect();
    Some(Polygon::new(exterior, interiors?))
}

/// Recursively map a `serde_json::Value` to an `MvtValue`. Numbers
/// prefer the signed-integer encoding when possible (matching the
/// proto layer's `int_value`) and fall back to `Double` for fractional
/// or out-of-range values.
fn json_to_mvt_value(v: &Json) -> MvtValue {
    match v {
        Json::Null => MvtValue::Null,
        Json::Bool(b) => MvtValue::Bool(*b),
        Json::String(s) => MvtValue::String(s.clone()),
        Json::Number(n) => {
            if let Some(i) = n.as_i64() {
                MvtValue::SInt(i)
            } else if let Some(f) = n.as_f64() {
                MvtValue::Double(f)
            } else {
                // Arbitrary-precision numbers are off in `serde_json`'s
                // default config, so this branch is effectively
                // unreachable — but it's cheap to surface as Null
                // rather than panic.
                MvtValue::Null
            }
        }
        Json::Array(items) => MvtValue::Array(items.iter().map(json_to_mvt_value).collect()),
        Json::Object(map) => {
            let mut out = HashMap::new();
            for (k, v) in map {
                out.insert(k.clone(), json_to_mvt_value(v));
            }
            MvtValue::Object(out)
        }
    }
}

