// Runs the vendored maplibre-style-spec expression test fixtures
// against our `style::expression` parser + evaluator.
//
// Most fixtures currently fail because our evaluator only models a
// few operators. Rather than skipping them, we maintain a list of
// fixtures known to fail at
// `tests/maplibre_expected_failures.txt`. The runner enforces both
// directions:
//
// * Listed fixtures must currently fail. If one now passes the
//   runner reports it as `unexpected-pass` and the test fails —
//   so adding an operator forces the contributor to prune the
//   manifest.
// * Unlisted fixtures must currently pass. New upstream fixtures
//   land as `unexpected-fail` and surface as test failures, which
//   is exactly the regression signal we want.
//
// Bootstrap mode (`MAPLIBRE_BOOTSTRAP_FAILURES=1`) regenerates the
// manifest from a current run instead of asserting. Use it once at
// initial setup, then commit; never again unless we accept a
// wholesale shift in upstream behavior.
//
// Phase 10 added the compile-shape comparison: in addition to
// `compiled.result` (success vs error) the runner now also checks
// `compiled.type`, `compiled.isFeatureConstant`,
// `compiled.isZoomConstant`, and — when the fixture supplies a
// `propertySpec` — the inferred type's compatibility with the
// declared property type. The compile shape only matters on
// `success` fixtures; error fixtures still pass on any error.

use std::collections::{BTreeSet, HashMap, HashSet};
use std::fs;
use std::path::{Path, PathBuf};

use geo::{LineString, MultiLineString, MultiPoint, MultiPolygon, Point, Polygon};
use serde_json::Value as Json;
use vec_map_kit::{
    mvt::{Feature, Geometry, Value as MvtValue},
    style::{
        EvalContext, Expr, Value as ExprValue,
        expression::{CanonicalTileID, ExprType, formatted_to_json},
        legacy::{convert_legacy_function, is_legacy_function},
    },
};
use walkdir::WalkDir;

