#[test]
fn run_upstream_expression_suite() {
    let root = fixtures_root();
    assert!(
        root.is_dir(),
        "missing fixtures at {}\n\
         run script/vendor_maplibre_fixtures.sh to vendor them.",
        root.display()
    );

    // Discover all fixture files. Sorting keeps the manifest and
    // summary output stable across runs.
    let mut fixtures: Vec<PathBuf> = WalkDir::new(&root)
        .into_iter()
        .filter_map(Result::ok)
        .filter(|e| e.file_type().is_file() && e.file_name() == "test.json")
        .map(|e| e.into_path())
        .collect();
    fixtures.sort();

    assert!(
        !fixtures.is_empty(),
        "found zero fixtures under {}",
        root.display()
    );

    // Execute every fixture, partitioning by outcome.
    let mut passing: BTreeSet<String> = BTreeSet::new();
    let mut failing: Vec<(String, String)> = Vec::new();
    for path in &fixtures {
        let id = relative_id(path);
        match run_fixture(path) {
            Outcome::Pass => {
                passing.insert(id);
            }
            Outcome::Fail(reason) => {
                failing.push((id, reason));
            }
        }
    }
    let failing_ids: BTreeSet<String> = failing.iter().map(|(id, _)| id.clone()).collect();

    let bootstrap = std::env::var(BOOTSTRAP_ENV).is_ok();
    if bootstrap {
        write_manifest(&failing_ids);
        eprintln!(
            "[bootstrap] wrote {} failing fixtures to {}",
            failing_ids.len(),
            MANIFEST_PATH
        );
        eprintln!(
            "[bootstrap] {} pass / {} fail / {} total",
            passing.len(),
            failing.len(),
            fixtures.len(),
        );
        return;
    }

    let manifest = read_manifest();

    // Listed in manifest but now passing.
    let unexpected_pass: Vec<&String> =
        manifest.iter().filter(|id| passing.contains(*id)).collect();

    // Failing but not listed in manifest.
    let unexpected_fail: Vec<&(String, String)> = failing
        .iter()
        .filter(|(id, _)| !manifest.contains(id))
        .collect();

    let expected_fail_count = failing.len() - unexpected_fail.len();

    eprintln!("maplibre-style-spec expression suite");
    eprintln!("  pass:              {}", passing.len());
    eprintln!("  expected-fail:     {expected_fail_count}");
    eprintln!("  unexpected-fail:   {}", unexpected_fail.len());
    eprintln!("  unexpected-pass:   {}", unexpected_pass.len());
    eprintln!("  total fixtures:    {}", fixtures.len());

    if !unexpected_fail.is_empty() {
        eprintln!("\nUnexpected failures (these fixtures are not in the manifest):");
        for (id, reason) in &unexpected_fail {
            eprintln!("  {id}: {reason}");
        }
    }
    if !unexpected_pass.is_empty() {
        eprintln!(
            "\nUnexpected passes (manifest still lists these as failing — \
             delete the manifest lines):"
        );
        for id in &unexpected_pass {
            eprintln!("  {id}");
        }
    }

    // When `MAPLIBRE_REPORT_MANIFEST=1` is set, print the failure
    // reason for every manifest-listed (expected-fail) fixture. This
    // is a triage aid for the cleanup work — `--nocapture` surfaces
    // these lines so we can decide whether each remaining entry
    // deserves a fix or a documented deferral.
    if std::env::var("MAPLIBRE_REPORT_MANIFEST").is_ok() {
        eprintln!("\nExpected-fail reasons (from manifest):");
        for (id, reason) in &failing {
            if manifest.contains(id) {
                eprintln!("  {id}: {reason}");
            }
        }
    }

    assert!(
        unexpected_fail.is_empty(),
        "{} fixture(s) failed without being in the manifest",
        unexpected_fail.len()
    );
    assert!(
        unexpected_pass.is_empty(),
        "{} manifest entry/entries no longer fail — prune them",
        unexpected_pass.len()
    );
}
