const FIXTURES_SUBDIR: &str = "tests/fixtures/maplibre-style-spec/expression";
const MANIFEST_PATH: &str = "tests/maplibre_expected_failures.txt";
const BOOTSTRAP_ENV: &str = "MAPLIBRE_BOOTSTRAP_FAILURES";

fn repo_root() -> PathBuf {
    // `CARGO_MANIFEST_DIR` is the crate root, which is also the
    // repo root for this single-crate project.
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn fixtures_root() -> PathBuf {
    repo_root().join(FIXTURES_SUBDIR)
}

fn manifest_path() -> PathBuf {
    repo_root().join(MANIFEST_PATH)
}

/// Convert an absolute fixture path back into the manifest's
/// `<op>/<case>` form.
fn relative_id(path: &Path) -> String {
    let root = fixtures_root();
    let rel = path
        .strip_prefix(&root)
        .expect("fixture path under fixtures root")
        .parent()
        .expect("test.json must live in <op>/<case>/")
        .to_string_lossy()
        .into_owned();
    // Normalize path separators to forward slashes so the manifest
    // is portable across OSes.
    rel.replace('\\', "/")
}

fn read_manifest() -> BTreeSet<String> {
    let path = manifest_path();
    if !path.exists() {
        return BTreeSet::new();
    }
    fs::read_to_string(&path)
        .expect("read manifest")
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .map(str::to_owned)
        .collect()
}

fn write_manifest(entries: &BTreeSet<String>) {
    let mut body = String::new();
    body.push_str(
        "# Fixtures from tests/fixtures/maplibre-style-spec/expression/\n\
         # that currently fail. The runner asserts these still fail and\n\
         # asserts every other fixture passes. Delete a line when an\n\
         # operator implementation makes the fixture pass.\n\
         #\n\
         # Auto-generated by `MAPLIBRE_BOOTSTRAP_FAILURES=1 cargo test\n\
         # --test maplibre_style_spec`. Edits below this line are\n\
         # preserved between regenerations only if you re-bootstrap\n\
         # with the same set.\n\n",
    );
    for entry in entries {
        body.push_str(entry);
        body.push('\n');
    }
    fs::write(manifest_path(), body).expect("write manifest");
}

