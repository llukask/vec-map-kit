/// Convert an [`ExprValue`] (eval result) back into JSON so we can
/// compare it uniformly against the fixture's expected output.
fn expr_value_to_json(v: &ExprValue) -> Json {
    match v {
        ExprValue::Null => Json::Null,
        ExprValue::Bool(b) => Json::Bool(*b),
        ExprValue::Number(n) => serde_json::Number::from_f64(*n)
            .map(Json::Number)
            .unwrap_or(Json::Null),
        ExprValue::String(s) => Json::String(s.clone()),
        ExprValue::Array(items) => Json::Array(items.iter().map(expr_value_to_json).collect()),
        ExprValue::Object(map) => {
            let mut out = serde_json::Map::new();
            for (k, v) in map {
                out.insert(k.clone(), expr_value_to_json(v));
            }
            Json::Object(out)
        }
        // `Formatted` is the only non-scalar runtime value the corpus
        // round-trips structurally; the shape matches upstream
        // `Formatted.toJSON()` so deep-compare just works.
        ExprValue::Formatted(f) => formatted_to_json(f),
        // Collator results never appear in `expected.outputs` —
        // fixtures consume them as the 3rd arg of comparisons or via
        // `resolved-locale`. Surface a placeholder rather than
        // panicking if one leaks through.
        ExprValue::Collator(_) => Json::String("<collator>".into()),
        // Color outputs round-trip as `[r*a, g*a, b*a, a]` —
        // upstream's `Color.toJSON()` premultiplies on the way out.
        // The expression layer stores straight RGBA; we apply the
        // premultiply here at the JSON boundary.
        ExprValue::Color([r, g, b, a]) => Json::Array(vec![
            serde_json::Number::from_f64(*r * *a)
                .map(Json::Number)
                .unwrap_or(Json::Null),
            serde_json::Number::from_f64(*g * *a)
                .map(Json::Number)
                .unwrap_or(Json::Null),
            serde_json::Number::from_f64(*b * *a)
                .map(Json::Number)
                .unwrap_or(Json::Null),
            serde_json::Number::from_f64(*a)
                .map(Json::Number)
                .unwrap_or(Json::Null),
        ]),
        // Resolved images round-trip as `{name, available}` —
        // upstream's `ResolvedImage.toJSON()` emits exactly this
        // shape and the `image/{basic,coalesce,compound}` fixtures
        // assert on the structural equality.
        ExprValue::Image(img) => {
            let mut o = serde_json::Map::new();
            o.insert("name".into(), Json::String(img.name.clone()));
            o.insert("available".into(), Json::Bool(img.available));
            Json::Object(o)
        }
    }
}

/// Deep-compare with the same precision shaping upstream's test
/// runner applies (`stripPrecision`): integer-valued numbers compare
/// exactly, everything else rounds to four decimal places before the
/// equality check. The upstream snippet is roughly
///
///     Math.abs(Math.round(x) - x) < 1e-10
///       ? Math.round(x)
///       : Number(x.toFixed(4))
///
/// so we mirror it. The earlier `1e-6 * scale` relative tolerance
/// was tighter than the corpus expects and made cubic-bezier and
/// exponential-interpolation outputs round-trip-fail by ~5e-6.
fn approx_eq(a: &Json, b: &Json) -> bool {
    match (a, b) {
        (Json::Number(x), Json::Number(y)) => {
            let (Some(xf), Some(yf)) = (x.as_f64(), y.as_f64()) else {
                return x == y;
            };
            // Apply upstream's `stripPrecision` first (6 decimal sig
            // figs, floor-rounded), then accept an extra ULP of slop
            // on the stripped values. The slop handles the boundary
            // cases where our eval and the fixture's recorded value
            // straddle a rounding boundary by ~1e-16 (e.g.
            // `0.9999999999999999` vs `1`); without it those would
            // strip differently and report as a per-input miscompare.
            let xs = strip_precision(xf);
            let ys = strip_precision(yf);
            if xs == ys {
                return true;
            }
            // Allow up to one "decimal sig fig" of post-strip drift —
            // 2e-6 of relative scale, with a 1.0 floor so values
            // near zero use absolute tolerance. The slop has to be
            // strictly greater than `1e-6 * scale` because the
            // `Math.floor`-based strip can leave two adjacent stripped
            // values exactly one quantum apart even when the raw
            // inputs differ by a single ULP.
            let scale = xs.abs().max(ys.abs()).max(1.0);
            (xs - ys).abs() <= 2e-6 * scale
        }
        (Json::Array(xs), Json::Array(ys)) => {
            xs.len() == ys.len() && xs.iter().zip(ys).all(|(x, y)| approx_eq(x, y))
        }
        (Json::Object(xs), Json::Object(ys)) => {
            xs.len() == ys.len()
                && xs
                    .iter()
                    .all(|(k, x)| ys.get(k).is_some_and(|y| approx_eq(x, y)))
        }
        _ => a == b,
    }
}

/// Mirror upstream's `stripPrecision` in `test/lib/json-diff.ts`: cut
/// each number down to 6 decimal significant figures so the fixture's
/// rounded `expected.outputs` line up with our full-precision evals.
///
/// Upstream uses `Math.floor` (not round-half) and runs the floor
/// twice in a row to absorb the IEEE-754 jitter that would otherwise
/// turn e.g. `8.16598 * 1e5 = 816597.9999…` into `816597` instead of
/// `816598`. We replicate the same "two flooring passes" pattern; a
/// single pass would diverge on a small handful of fixture values
/// (notably the cubic-bezier and exponential ramps).
fn strip_precision(x: f64) -> f64 {
    const DECIMAL_SIG_FIGS: i32 = 6;
    if !x.is_finite() || x == 0.0 {
        return x;
    }
    // The "decimal sig figs" form means: total digits after counting
    // both whole and fractional, but with the floor anchored at the
    // decimal point — see the upstream comment "strips down to 6
    // decimal sigfigs but stops at decimal point".
    let order = x.abs().log10().ceil() as i32;
    let exp = (DECIMAL_SIG_FIGS - order).max(0);
    let multiplier = 10f64.powi(exp);
    let first = (x * multiplier).floor() / multiplier;
    (first * multiplier).floor() / multiplier
}

/// Returns true if the expected output is an error sentinel
/// `{"error": "..."}`.
fn is_error_marker(v: &Json) -> bool {
    v.as_object()
        .is_some_and(|o| o.len() == 1 && o.contains_key("error"))
}

// ==============================================================================
// propertySpec — type mapping
// ==============================================================================
//
// Each fixture may carry a `propertySpec` block describing the style
// property the expression should produce. We map it onto an
// [`ExprType`] so the compile-time check ("is the expression's result
// type assignable to the declared property type?") becomes a one-line
// comparison.

/// Convert a `propertySpec` block into the equivalent [`ExprType`].
/// Returns `None` if the shape isn't one Phase 10 recognizes — the
/// runner falls back to skipping the propertySpec check rather than
/// inventing a constraint.
fn parse_property_spec_type(spec: &Json) -> Option<ExprType> {
    let obj = spec.as_object()?;
    let kind = obj.get("type")?.as_str()?;
    Some(match kind {
        "number" => ExprType::Number,
        "string" => ExprType::String,
        "boolean" => ExprType::Boolean,
        "color" => ExprType::Color,
        "formatted" => ExprType::Formatted,
        "resolvedImage" => ExprType::ResolvedImage,
        "object" => ExprType::Object,
        "array" => {
            let item = obj
                .get("value")
                .and_then(Json::as_str)
                .map(item_type_from_str);
            let length = obj.get("length").and_then(Json::as_u64).map(|n| n as usize);
            ExprType::Array(item.map(Box::new), length)
        }
        // Aggregate spec types we don't model as a dedicated variant.
        // Upstream renders them with the short name (`numberArray`)
        // while structurally they're typed arrays.
        "numberArray" => ExprType::Array(Some(Box::new(ExprType::Number)), None),
        "colorArray" => ExprType::Array(Some(Box::new(ExprType::Color)), None),
        _ => return None,
    })
}

fn item_type_from_str(s: &str) -> ExprType {
    match s {
        "number" => ExprType::Number,
        "string" => ExprType::String,
        "boolean" => ExprType::Boolean,
        // Fallback for anything else — treat as the top type so the
        // outer assignability check doesn't reject on item type.
        _ => ExprType::Value,
    }
}

/// "Is the actual type assignable to the expected type?" — implements
/// upstream's `checkSubtype` minus the implicit-coercion edges (those
/// require parser-driven cast insertion which is out of scope for
/// Phase 10's first cut). The rules:
///
/// * Identical types match.
/// * The top type `value` accepts anything.
/// * Array structure: items match (or expected has no item type),
///   length matches (or expected has no length).
/// * `formatted` accepts `string` (upstream implicitly wraps it).
/// * `resolvedImage` accepts `string` (same reason).
fn type_is_assignable(expected: &ExprType, actual: &ExprType) -> bool {
    if expected == actual {
        return true;
    }
    match (expected, actual) {
        (ExprType::Value, _) => true,
        // Implicit coercion edges that the spec parser inserts for
        // free. We accept the actual type as a stand-in for the
        // expected; the fixture's eval phase then exercises whatever
        // the implicit coercion would have produced. The fixtures that
        // depend on the resulting *evaluated* value still need actual
        // cast insertion and stay in the manifest until that lands.
        // `formatted` accepts strings and the top type `value` —
        // `format/implicit-coerce` and `format/implicit-omit` rely on
        // this. We deliberately exclude `number → formatted` so
        // `format/implicit-assert` (a bare `["number", get p]`)
        // surfaces as a typecheck error — upstream's implicit-cast
        // chain doesn't tolerate a numeric-typed expression in a
        // formatted slot without an explicit `to-string` first.
        (ExprType::Formatted, ExprType::String)
        | (ExprType::Formatted, ExprType::Value)
        | (ExprType::ResolvedImage, ExprType::String)
        | (ExprType::ResolvedImage, ExprType::Value)
        | (ExprType::Color, ExprType::String)
        | (ExprType::Color, ExprType::Value)
        | (ExprType::Number, ExprType::Value)
        | (ExprType::String, ExprType::Value)
        | (ExprType::Boolean, ExprType::Value)
        | (ExprType::Object, ExprType::Value) => true,
        (ExprType::Array(e_item, e_len), ExprType::Array(a_item, a_len)) => {
            // Empty-array literals (length 0) are assignable to any
            // typed array — the `literal/infer-empty-array-type`
            // fixture pins this. The empty array's *item* type comes
            // out as `value` in our inference, which would otherwise
            // fail the assignability check against a concrete item
            // type like `number`.
            if matches!(a_len, Some(0)) {
                return true;
            }
            let item_ok = match (e_item, a_item) {
                (None, _) => true,
                (Some(_), None) => false,
                (Some(e), Some(a)) => type_is_assignable(e, a),
            };
            let len_ok = match (e_len, a_len) {
                (None, _) => true,
                (Some(_), None) => false,
                (Some(e), Some(a)) => e == a,
            };
            item_ok && len_ok
        }
        // `Array` expected, `value` actual: same implicit-cast story
        // as the scalar shapes above. Without the actual coercion
        // wrapper the eval might still mismatch, but at the *type*
        // level the expression is acceptable.
        (ExprType::Array(_, _), ExprType::Value) => true,
        _ => false,
    }
}

/// Normalize fixture `expected.compiled.type` strings so they line up
/// with our renderer's output. The only divergences are `colorArray`
/// and `numberArray`, which upstream emits as the short alias but
/// structurally are typed arrays.
fn normalize_compile_type(s: &str) -> String {
    match s {
        "numberArray" => "array<number>".into(),
        "colorArray" => "array<color>".into(),
        other => other.to_string(),
    }
}

/// Wrap an expression in the implicit cast upstream's parser would
/// insert when the expression's static type doesn't exactly match the
/// declared property type but a known one-step coercion exists. The
/// coercion edges we model — `string|value → formatted`,
/// `string|value → color`, `string|value → resolvedImage`,
/// `value → string|number|boolean`, and array-shape pinning for
/// untyped/empty arrays — match the upstream `Step.parse`,
/// `Interpolate.parse`, and parent-expression cast machinery, which
/// is what lets a bare `["get", "p"]` evaluate as `"formatted"` under
/// a `formatted` propertySpec.
///
/// The actual *runtime* wrapping is bookkeeping for the type check
/// only: we never need to alter eval, since the wrap operators
/// (`to-string`/`to-color`/`format`/`array`) all evaluate
/// transparently when the inner already produces the target type.
fn apply_implicit_cast(expr: Expr, expected: &ExprType) -> Expr {
    let actual = expr.result_type();
    // Already exact: nothing to do.
    if actual == *expected {
        return expr;
    }
    match (expected, &actual) {
        // String coercion. `value`/`number`/`boolean` → `string` via
        // implicit `to-string`. Property-level casts use the
        // coercion form (silent on null → ""), which is what
        // `to-string/implicit` and `coalesce/inference` expect.
        // The interpolate-stop case where a stop output must be
        // numerically asserted lives inside `interpolate` itself
        // (see [`enforce_numeric_stop`]) rather than at the property
        // boundary.
        (ExprType::String, _) => Expr::Coerce {
            kind: vec_map_kit::style::expression::CoerceKind::ToString,
            values: vec![expr],
        },
        (ExprType::Number, _) => Expr::Coerce {
            kind: vec_map_kit::style::expression::CoerceKind::ToNumber,
            values: vec![expr],
        },
        (ExprType::Boolean, _) => Expr::Coerce {
            kind: vec_map_kit::style::expression::CoerceKind::ToBoolean,
            values: vec![expr],
        },
        // Color — wrap in `to-color`. The runtime accepts named/hex
        // strings and `[r,g,b,a]` arrays, which is exactly what the
        // `case/interpolated-output` fallback (`"#fcaf3e"`) needs.
        (ExprType::Color, _) => Expr::ToColor(vec![expr]),
        // Formatted — wrap in a single-section `format`. The format
        // operator already stringifies non-formatted inputs at eval
        // time, so the wrap is purely a typing fixup.
        (ExprType::Formatted, _) => wrap_format_single_section(expr),
        // Resolved image — wrap in `image`. The runtime accepts a
        // string-yielding inner.
        (ExprType::ResolvedImage, _) => Expr::Image(Box::new(expr)),
        // Typed-array shape pinning. The fixture `array/implicit-2`
        // expects `["get", "array"]` (statically `value`) to compile
        // as `array<string>` under an `array` propertySpec, by way
        // of an implicit `["array", item, value]` wrap. We only wrap
        // when the inner is `value` or an empty literal array — a
        // fully-typed array (e.g. the explicit `["array", "number",
        // 2, …]` in `typecheck/array-item-subtyping`) already has
        // the right shape, and wrapping it in another `array`
        // assertion would collapse the inner's item-type/length down
        // to the outer's propertySpec-less form. Empty arrays decay
        // to `array<value, 0>` from `literal_value_type`; promoting
        // them through the implicit cast is what
        // `literal/infer-empty-array-type` pins.
        (ExprType::Array(item, length), actual_ty) if array_needs_wrapping(expected, actual_ty) => {
            // Map the expected item type back into the parse-time
            // [`ItemType`] enum. Anything outside the trio
            // (number/string/boolean) leaves the array untyped.
            let item_type = item.as_deref().and_then(|t| match t {
                ExprType::Number => Some(vec_map_kit::style::expression::ItemType::Number),
                ExprType::String => Some(vec_map_kit::style::expression::ItemType::String),
                ExprType::Boolean => Some(vec_map_kit::style::expression::ItemType::Boolean),
                _ => None,
            });
            Expr::ArrayAssert {
                item_type,
                length: *length,
                values: vec![expr],
            }
        }
        // No implicit edge for this pair; fall through unchanged. The
        // result type stays whatever it inferred to.
        _ => expr,
    }
}

/// Wrap an array output in upstream's `numberArray` / `colorArray`
/// JSON shape — `{"values": [...]}`. The expression engine has no
/// dedicated aggregate value type for these, so we materialize the
/// wrapping at the JSON boundary instead.
fn wrap_aggregate_values(v: Json) -> Json {
    let Json::Array(items) = v else {
        return v;
    };
    let mut o = serde_json::Map::new();
    o.insert("values".into(), Json::Array(items));
    Json::Object(o)
}

/// Per-argument coalesce type check. Upstream's `Coalesce.parse`
/// walks each operand and asserts it's assignable to the expression's
/// inferred type (which is the join of the first operand's type and
/// the propertySpec). The fixtures `coalesce/argument-type-mismatch`
/// (literal `5` against an inferred `string`) and `coalesce/infer-
/// array-type` (literal `null` against an inferred `array<string>`)
/// pin compile-time rejection on a per-argument basis.
///
/// Returns `Err` with a short reason when one of the operands isn't
/// assignable. Non-coalesce expressions sail through with `Ok`.
fn check_coalesce_arg_types(expr: &Expr, expected: &ExprType) -> Result<(), String> {
    let Expr::Coalesce(args) = expr else {
        return Ok(());
    };
    for (i, arg) in args.iter().enumerate() {
        let t = arg.result_type();
        if !type_is_assignable(expected, &t) {
            return Err(format!(
                "coalesce arg #{i}: expected {} but found {} instead",
                expected.to_spec_string(),
                t.to_spec_string()
            ));
        }
    }
    Ok(())
}

/// Does an array-typed expression need an implicit `array` wrapper to
/// match the propertySpec's expected shape? Three cases drive a wrap:
///
/// * the actual is `value` — the expression is type-erased and the
///   wrap pins it to the expected item type / length;
/// * the actual is an empty-array literal (`array<value, 0>`) — the
///   wrap promotes it to the expected item type;
/// * the expected drops a length the actual pinned (open vs sized) —
///   the wrap normalizes the rendered type back to the open form.
fn array_needs_wrapping(expected: &ExprType, actual: &ExprType) -> bool {
    let ExprType::Array(_, _) = expected else {
        return false;
    };
    matches!(actual, ExprType::Value | ExprType::Array(_, Some(0)))
}

/// Build a single-section `format` wrapping a bare scalar. The format
/// operator at parse-time normally requires `[text, options]` pairs
/// (or bare text strings as a shorthand); upstream's implicit cast
/// for `string → formatted` is the same as a hand-written
/// `["format", expr]`, which is what we synthesize here.
fn wrap_format_single_section(expr: Expr) -> Expr {
    use vec_map_kit::style::expression::FormatSection;
    Expr::Format(vec![FormatSection {
        text: Box::new(expr),
        font_scale: None,
        text_font: None,
        text_color: None,
        vertical_align: None,
    }])
}

